'use strict';
const { app, BrowserWindow, clipboard } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { exchange } = require('../src/integrations/client');
const { saveScreenshot } = require('./helpers.cjs');
const root = process.env.ISLAND_HUD_TEST_ROOT;
const checks = [], screenshots = [];
let overlay;
app.on('browser-window-created', (_event, win) => { if (!overlay) overlay = win; });
require('../src/main.js');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(check, timeout = 6000) { const end = Date.now() + timeout; while (Date.now() < end) { if (await check()) return; await pause(30); } throw new Error('Upgrade UI condition timed out'); }
app.whenReady().then(async () => {
  const js = source => overlay.webContents.executeJavaScript(source), descriptor = path.join(root, 'integration-v2.json');
  let controller;
  try {
    await until(() => overlay && !overlay.webContents.isLoading()); await until(() => js('!!window.__islandApp'));
    await until(() => fs.existsSync(descriptor));
    const request = { provider: 'dsh', id: 'ime-question', sessionId: 'upgrade-session', kind: 'question', payload: { cwd: 'C:\\中文 路径\\升级项目', callId: 'ime-call', questions: [{ id: 'choice', question: '请选择验证项，并在同一题补充中文说明。', multiSelect: true, options: [{ label: 'X', description: '第一项的可见中文说明' }, { label: 'Z', description: '第二项的可见中文说明' }] }] } };
    const answer = exchange(request, { descriptor });
    await until(() => js('!!document.querySelector("fieldset[data-id=choice]")'));
    assert.match(await js('document.querySelector(".option-copy").textContent'), /可见中文说明/);
    await js('document.querySelector("input[value=X]").click();document.querySelector("input[value=Z]").click();window.originalTextarea=document.querySelector("textarea");window.originalTextarea.value="中文与多选验收";window.originalTextarea.dispatchEvent(new Event("input",{bubbles:true}))');
    assert.match(await js('document.querySelector(".selection-count").textContent'), /2/);
    overlay.webContents.send('dsh:update', [{ id: '["dsh","upgrade-session"]', rawId: 'upgrade-session', provider: 'dsh', title: '日志更新时保留草稿', phase: 'running', updatedAt: Date.now() }]);
    assert.equal(await js('window.originalTextarea===document.querySelector("textarea")'), true);
    await js('document.querySelector("[data-native-action=next]").click()');
    assert.match(await js('document.querySelector(".native-review").textContent'), /请选择验证项/);
    await js('document.dispatchEvent(new CompositionEvent("compositionstart",{bubbles:true}));document.dispatchEvent(new KeyboardEvent("keydown",{key:"Enter",ctrlKey:true,isComposing:true,bubbles:true}))');
    await pause(100); assert.equal((await js('window.island.native.snapshot()')).length, 1);
    await js('document.dispatchEvent(new CompositionEvent("compositionend",{bubbles:true}));document.dispatchEvent(new KeyboardEvent("keydown",{key:"Enter",ctrlKey:true,bubbles:true}))');
    assert.deepEqual((await answer).answers, [{ id: 'choice', selected: ['X','Z'], custom: '中文与多选验收' }]);
    checks.push('visible descriptions, exact Chinese multi-select, stable textarea and IME-safe Ctrl+Enter');
    await exchange({ provider: 'dsh', id: 'confirmed-event', sessionId: 'upgrade-session', kind: 'event', payload: { event: 'QuestionAnswered', requestId: 'ime-question', outcome: 'answered' } }, { descriptor });
    await until(() => js('document.querySelector("#notch").className==="s-approved"'));
    assert.match(await js('document.querySelector("[data-layer=approved]").textContent'), /客户端已收到答案/);
    checks.push('a success result appears only after the native QuestionAnswered acknowledgement');
    await pause(1300);
    controller = new AbortController();
    const held = exchange({ ...request, id: 'held-question' }, { descriptor, signal: controller.signal });
    await until(() => js('!!document.querySelector("fieldset")'));
    await js('document.querySelector("[data-native-action=collapse]").click()'); await pause(650);
    assert.equal(await js('window.__islandApp.getState().scene'), 'compact');
    overlay.webContents.send('dsh:update', []); await pause(150);
    assert.equal(await js('window.__islandApp.getState().scene'), 'compact');
    controller.abort(); await held;
    checks.push('a manually collapsed request stays collapsed across repeated session snapshots');
    await js('window.island.settings.open()');
    let settingsWindow;
    await until(() => { settingsWindow = BrowserWindow.getAllWindows().find(win => win !== overlay); return settingsWindow && !settingsWindow.webContents.isLoading(); });
    const settingsJS = source => settingsWindow.webContents.executeJavaScript(source);
    await until(() => settingsJS('document.querySelector("#version").textContent.includes("v")'));
    await settingsJS('document.querySelector("[data-tab=display]").click();document.querySelector("#panelDensity").value="compact";document.querySelector("#settingsTheme").value="dark";document.querySelector("#settingsTheme").dispatchEvent(new Event("input",{bubbles:true}))');
    assert.equal((await js('window.island.settings.get()')).panelDensity, 'comfortable');
    assert.equal(await settingsJS('document.body.classList.contains("light")'), false);
    await pause(300);
    await saveScreenshot(settingsWindow, path.join(root, 'settings-dark-preview.png')); screenshots.push('settings-dark-preview.png');
    settingsWindow.close(); await pause(150);
    assert.equal((await js('window.island.settings.get()')).panelDensity, 'comfortable');
    checks.push('unsaved settings preview uses the real renderer and cancellation leaves the live density unchanged');
    await js('window.island.settings.open()'); await until(() => { settingsWindow = BrowserWindow.getAllWindows().find(win => win !== overlay); return settingsWindow && !settingsWindow.webContents.isLoading(); });
    await until(() => settingsJS('document.querySelector("#version").textContent.includes("v")'));
    await settingsJS('document.querySelector("[data-tab=display]").click();document.querySelector("#panelDensity").value="compact";document.querySelector("#settingsTheme").value="light";document.querySelector("#save").click()');
    await until(() => js('window.__islandApp.getState().layout.width===440'));
    assert.equal((await js('window.island.settings.get()')).settingsVersion, 3);
    checks.push('saved appearance broadcasts immediately, resizes the overlay and persists version-3 settings');
    await saveScreenshot(settingsWindow, path.join(root, 'settings-light.png')); screenshots.push('settings-light.png');
    const before = clipboard.readText();
    await settingsJS('document.querySelector("#copyDiag").click()'); await until(() => clipboard.readText() !== before);
    assert.match(clipboard.readText(), /Island HUD/);
    checks.push('the reorganized settings retain working diagnostics actions');
    fs.writeFileSync(path.join(root, 'upgrade-result.json'), JSON.stringify({ status: 'passed', checks, screenshots, note: 'Own GUI and protocol fixtures; native DSH verification is separate.' }, null, 2));
  } catch (error) { controller?.abort(); fs.writeFileSync(path.join(root, 'upgrade-result.json'), JSON.stringify({ status: 'failed', checks, error: error.stack }, null, 2)); process.exitCode = 1; }
  finally { app.quit(); }
});
