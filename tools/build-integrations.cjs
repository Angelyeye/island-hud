'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
// The lib copies are build products; the banner keeps them from being edited
// as if they were source.
const BANNER = '// AUTO-GENERATED by tools/build-integrations.cjs from src/integrations — edit the source, then run npm run build:integrations.\n';
for (const provider of ['dsh', 'zcode', 'claude']) {
  const lib = path.join(root, `integrations/${provider}/lib`);
  fs.mkdirSync(lib, { recursive: true });
  for (const name of ['client', 'contract']) {
    const source = fs.readFileSync(path.join(root, `src/integrations/${name}.js`), 'utf8').replace("require('./contract')", "require('./contract.cjs')");
    fs.writeFileSync(path.join(lib, `${name}.cjs`), BANNER + source);
  }
}
console.log('DSH, ZCode and Claude bundles prepared: integrations/dsh, integrations/zcode, integrations/claude');
